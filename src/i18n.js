export const LANGS = ['ua', 'ru', 'en'];

export const adNo = (id) => String(id).padStart(8, '0');

export function t(lang, key, vars = {}) {
  if (vars.id != null && vars.no == null) vars = { ...vars, no: adNo(vars.id) };
  const dict = T[lang] || T.ua;
  let s = dict[key] ?? T.ua[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// Find which menu button a text corresponds to, in any language.
export function menuKeyOf(text) {
  for (const lang of LANGS) {
    for (const key of ['menu_new', 'menu_my', 'menu_report', 'menu_admin', 'menu_help', 'menu_panel', 'menu_invite', 'menu_idea']) {
      if (T[lang][key] === text) return key;
    }
  }
  return null;
}
